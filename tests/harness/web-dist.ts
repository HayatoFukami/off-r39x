// ---- expected `_headers` --------------------------------------------------------------------

export const HEADERS_COMMENT = "# Generated by scripts/generate-web-headers.mts. Do not edit.";

/** The six protected prefixes (SEC-WEB-009). Each is written as the prefix itself and as `<prefix>/*`. */
export const PROTECTED_PREFIXES = [
  "/account",
  "/auth",
  "/purchase",
  "/mypage",
  "/admin",
  "/staff",
] as const;

/** Rule paths after the `/*` rule, in the fixed order of the generated file. */
export const PROTECTED_RULE_PATHS: readonly string[] = PROTECTED_PREFIXES.flatMap((prefix) => [
  prefix,
  `${prefix}/*`,
]);

export const NO_STORE = "no-store, private, max-age=0";
export const DEFAULT_REFERRER_POLICY = "strict-origin-when-cross-origin";
export const PROTECTED_REFERRER_POLICY = "no-referrer";

/** Security headers of the `/*` rule other than the CSP, in file order (SPEC-140 section 22 / 22.1). */
export const BASE_SECURITY_HEADERS: readonly (readonly [string, string])[] = [
  ["X-Content-Type-Options", "nosniff"],
  ["Referrer-Policy", DEFAULT_REFERRER_POLICY],
  ["X-Frame-Options", "DENY"],
  ["Strict-Transport-Security", "max-age=63072000; includeSubDomains"],
  ["Cross-Origin-Opener-Policy", "same-origin"],
  ["Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=()"],
];

/** `hashes` are CSP hash sources without quotes, e.g. `sha256-AbC=`. `imgOrigins` are normalised origins. */
export function cspValue(
  hashes: readonly string[] = [],
  imgOrigins: readonly string[] = [],
): string {
  const script = ["'self'", ...hashes.map((hash) => `'${hash}'`)].join(" ");
  const img = ["'self'", "data:", "blob:", ...imgOrigins].join(" ");
  return [
    "default-src 'self'",
    `script-src ${script}`,
    "script-src-attr 'none'",
    "style-src 'self' 'unsafe-inline'",
    `img-src ${img}`,
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "frame-ancestors 'none'",
    "frame-src 'none'",
    "form-action 'self'",
    "manifest-src 'self'",
    "worker-src 'self' blob:",
    "media-src 'self' blob:",
    "upgrade-insecure-requests",
  ].join("; ");
}

export interface HeadersOptions {
  readonly hashes?: readonly string[];
  readonly imgOrigins?: readonly string[];
}

/** The complete `dist/_headers` file for the given inline-script hashes and Sponsor image origins. */
export function expectedHeadersFile(options: HeadersOptions = {}): string {
  const rules: string[] = [
    [
      "/*",
      `  Content-Security-Policy: ${cspValue(options.hashes, options.imgOrigins)}`,
      ...BASE_SECURITY_HEADERS.map(([name, value]) => `  ${name}: ${value}`),
    ].join("\n"),
    ...PROTECTED_RULE_PATHS.map((path) =>
      [
        path,
        `  Cache-Control: ${NO_STORE}`,
        "  Pragma: no-cache",
        `  Referrer-Policy: ${PROTECTED_REFERRER_POLICY}`,
      ].join("\n"),
    ),
  ];
  return `${HEADERS_COMMENT}\n${rules.join("\n\n")}\n`;
}

export function sha256Source(body: string): string {
  return `sha256-${createHash("sha256").update(body, "utf8").digest("base64")}`;
}

