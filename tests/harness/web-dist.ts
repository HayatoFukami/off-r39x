// ---- raw HTTP ---------------------------------------------------------------------------------

export interface RawResponse {
  readonly status: number;
  readonly headers: Readonly<Record<string, string | string[] | undefined>>;
  readonly rawHeaders: readonly string[];
  readonly body: string;
}

/** An HTTP request that sends `path` exactly as given (fetch and URL would normalise `..` and `%2e`). */
export function rawRequest(
  port: number,
  method: string,
  path: string,
  options: { readonly headers?: Readonly<Record<string, string>> } = {},
): Promise<RawResponse> {
  return new Promise((resolve, reject) => {
    const req = request(
      { host: "127.0.0.1", port, method, path, headers: options.headers, agent: false },
      (res) => {
        const chunks: Buffer[] = [];
        res.on("data", (chunk: Buffer) => chunks.push(chunk));
        res.on("end", () =>
          resolve({
            status: res.statusCode ?? 0,
            headers: res.headers,
            rawHeaders: res.rawHeaders,
            body: Buffer.concat(chunks).toString("utf8"),
          }),
        );
        res.on("error", reject);
      },
    );
    req.setTimeout(15_000, () => req.destroy(new Error("request timeout")));
    req.on("error", reject);
    req.end();
  });
}

/** How many header lines of this name the response carries (a duplicate header would count twice). */
export function headerLines(response: RawResponse, name: string): number {
  let count = 0;
  for (let i = 0; i < response.rawHeaders.length; i += 2) {
    if ((response.rawHeaders[i] ?? "").toLowerCase() === name.toLowerCase()) count += 1;
  }
  return count;
}

export function headerValue(response: RawResponse, name: string): string | undefined {
  const value = response.headers[name.toLowerCase()];
  return Array.isArray(value) ? value.join(", ") : value;
}

// ---- the serving child process ----------------------------------------------------------------

export interface RunningServer {
  readonly port: number;
  /** Everything the process wrote to stdout and stderr so far. */
  output(): string;
  stop(): Promise<void>;
}

const READY = /^READY http:\/\/127\.0\.0\.1:(\d+)$/m;

/** Starts scripts/serve-web-dist.mts and resolves when it prints its READY line. */
export function startServe(dir: string, args: readonly string[] = []): Promise<RunningServer> {
  return new Promise((resolve, reject) => {
    const hasPort = args.includes("--port");
    const child: ChildProcess = spawn(
      process.execPath,
      [
        scriptPath("serve-web-dist.mts"),
        "--dir",
        dir,
        ...(hasPort ? [] : ["--port", "0"]),
        ...args,
      ],
      { cwd: REPO_ROOT, stdio: ["ignore", "pipe", "pipe"] },
    );
    let out = "";
    let settled = false;
    const append = (chunk: Buffer): void => {
      out += chunk.toString("utf8");
      const match = READY.exec(out);
      if (match && !settled) {
        settled = true;
        clearTimeout(timer);
        resolve({
          port: Number(match[1]),
          output: () => out,
          stop: () =>
            new Promise<void>((done) => {
              if (child.exitCode !== null || child.signalCode !== null) return done();
              child.once("exit", () => done());
              child.kill();
            }),
        });
      }
    };
    child.stdout?.on("data", append);
    child.stderr?.on("data", append);
    const fail = (reason: string): void => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      child.kill();
      reject(new Error(`serve-web-dist: ${reason}\n${out}`));
    };
    const timer = setTimeout(() => fail("READY line not printed within 20 s"), 20_000);
    child.once("exit", (code) => fail(`exited with ${String(code)} before READY`));
    child.once("error", (error) => fail(error.message));
  });
}
